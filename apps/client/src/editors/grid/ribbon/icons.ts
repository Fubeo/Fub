let mounted = 0;
let teardowns: Teardown[] = [];

/// Registra le figure per una barra che si monta; la teardown la smonta.
export function useRibbonIcons(): Teardown {
  if (mounted === 0) teardowns = Object.entries(RIBBON_ICONS).map(([name, paths]) => registerIcon(name, paths));
  mounted += 1;
  let released = false;
  return () => {
    if (released) return;
    released = true;
    mounted -= 1;
    if (mounted > 0) return;
    for (const teardown of teardowns) teardown();
    teardowns = [];
  };
}
